import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';

const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:850}});
const url=process.env.TEST_URL||'http://127.0.0.1:4176';
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
try{
 await page.goto(url);
 await page.locator('#new-file').waitFor();
 assert.equal(await page.locator('#tab-source').textContent(),'duck.py');
 assert.match(await page.evaluate(()=>localStorage.getItem('build1234.code')),/Puddle the duck/);
 assert.equal(await page.locator('#tab-preview').textContent(),'Preview');
 assert.equal(await page.locator('.document-tab .tab').count(),2);
 await page.locator('#run').click();
 await page.waitForFunction(()=>document.querySelector('#model-state').textContent==='result',null,{timeout:240000});
 assert.match(await page.locator('#cad-view').textContent(),/Puddle the duck/);
 await page.locator('#toggle-split').click();
 assert.equal(await page.locator('.document-tab .is-active').count(),2);
 assert.equal(await page.locator('[role="tab"][aria-selected="true"]').count(),2);
 assert.ok(await page.locator('#editor').isVisible());
 assert.ok(await page.locator('#cad-view canvas').isVisible());
 await fs.mkdir('test-artifacts',{recursive:true});
 await page.screenshot({path:'test-artifacts/duck-workbench-split.png'});
 await page.locator('#tab-source').click();
 assert.equal(await page.locator('#toggle-split').getAttribute('aria-pressed'),'false');
 assert.equal(await page.locator('.document-tab .is-active').count(),1);
 assert.ok(await page.locator('#editor').isVisible());
 assert.equal(await page.locator('#cad-view canvas').isVisible(),false);
 await page.keyboard.press('ArrowRight');
 assert.ok(await page.locator('#cad-view canvas').isVisible());
 assert.equal(await page.locator('#editor').isVisible(),false);
 await page.locator('#toggle-split').click();
 await page.locator('#tab-preview').click();
 assert.equal(await page.locator('#toggle-split').getAttribute('aria-pressed'),'false');
 assert.equal(await page.locator('#tab-preview').getAttribute('aria-selected'),'true');
 await page.locator('#new-file').click();
 assert.equal(await page.locator('#tab-source').textContent(),'untitled.py');
 assert.equal(await page.evaluate(()=>localStorage.getItem('build1234.code')),'');
 await page.keyboard.insertText('# keep these edits');
 await page.locator('#new-file').click();
 assert.equal(await page.locator('#tab-source').textContent(),'untitled-2.py');
 assert.equal(await page.evaluate(()=>localStorage.getItem('build1234.code')),'');
 await page.getByRole('treeitem',{name:'◇  untitled.py',exact:true}).click();
 assert.equal(await page.evaluate(()=>localStorage.getItem('build1234.code')),'# keep these edits');
 await page.locator('input[webkitdirectory]').setInputFiles(path.resolve('tests/fixtures/project'));
 await page.locator('#new-file').click();
 assert.equal(await page.locator('#tab-source').textContent(),'untitled-3.py');
 assert.ok(await page.getByRole('treeitem',{name:/untitled-3.py/}).isVisible());
 await page.getByRole('treeitem',{name:'◇  untitled.py',exact:true}).click();
 assert.equal(await page.evaluate(()=>localStorage.getItem('build1234.code')),'# keep these edits');
 await page.reload();
 await page.locator('#new-file').waitFor();
 assert.equal(await page.locator('#tab-source').textContent(),'untitled.py');
 assert.equal(await page.evaluate(()=>localStorage.getItem('build1234.code')),'# keep these edits');
 assert.equal(await page.locator('.shell-brand #about').textContent(),'?');
 await page.getByRole('button',{name:'About Duckbench',exact:true}).click();
 await page.frameLocator('#about-dialog iframe').getByRole('heading',{name:'Application license'}).waitFor();
 await page.locator('#close-about').click();
 await page.setViewportSize({width:390,height:800});
 assert.ok(await page.locator('#about').isVisible());
 assert.ok(await page.locator('#new-file').isVisible());
 await page.screenshot({path:'test-artifacts/workbench-narrow.png'});
 assert.deepEqual(errors,[]);
 console.log('Workbench: default duck render, split/tab selection, unique new files, preserved edits, workspace files, and relocated About passed.');
}finally{await browser.close();}
