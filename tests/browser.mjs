import { chromium } from 'playwright';

import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:process.env.TEST_BROWSER_CHANNEL||'chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage();
page.on('console',msg=>console.log('browser:',msg.type(),msg.text().slice(0,500)));
page.on('pageerror',error=>console.error('PAGE ERROR',error));
await page.goto(process.env.TEST_URL||'http://127.0.0.1:5173');
const monitor=setInterval(async()=>console.log('STATUS',await page.locator('#runtime-status').textContent(),(await page.locator('#logs').textContent()).slice(-600)),15000);
try {
 await page.locator('input[webkitdirectory]').setInputFiles(path.resolve('tests/fixtures/project'));
 await page.locator('summary').filter({hasText:'project'}).click();
 await page.getByRole('treeitem',{name:/model.py/}).click();
 await page.locator('#run').click();
 await page.locator('#preview-loading').waitFor({state:'visible'});
 assert.match(await page.locator('#preview-loading').textContent(),/first run downloads Python/);
 assert.equal(await page.locator('#empty-state').isVisible(),false);
 await fs.mkdir('test-artifacts',{recursive:true});
 await page.screenshot({path:'test-artifacts/first-load.png'});
 await page.waitForFunction(()=>document.querySelector('#model-state').textContent==='result', null, {timeout:240000});
 if(await page.locator('#error-banner').isVisible())throw new Error(await page.locator('#logs').textContent());
 console.log('UI rendered',await page.locator('#elapsed').textContent());
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#step').click();
 const download=await downloadPromise;
 console.log('STEP download',download.suggestedFilename());
 // A rebuild preserves the existing model and uses compact toolbar progress.
 const firstCanvas=await page.locator('.cad-instance').getAttribute('id');
 await page.locator('#tab-source').click();
 await page.locator('#editor .view-lines').click();
 await page.keyboard.press('Meta+End');
 await page.keyboard.insertText('\nimport time\ntime.sleep(2)\n');
 await page.locator('#tab-preview').click();
 await page.locator('#refresh-preview').click();
 await page.locator('#preview-progress').waitFor({state:'visible'});
 assert.equal(await page.locator('#preview-loading').isVisible(),false);
 assert.equal(await page.locator('.cad-instance').getAttribute('id'),firstCanvas);
 assert.ok(await page.locator('#cad-view canvas').isVisible());
 await page.screenshot({path:'test-artifacts/rebuilding.png'});
 await page.locator('#toggle-split').click();
 await page.locator('#editor .view-lines').click();
 await page.keyboard.press('Meta+End');
 await page.keyboard.insertText('\n# Edited during the build\n');
 await page.waitForFunction(()=>!document.querySelector('#run').disabled);
 await page.locator('#refresh-preview').waitFor({state:'visible'});
 await page.locator('#refresh-preview').click();
 await page.waitForFunction(()=>!document.querySelector('#run').disabled);
 assert.equal(await page.locator('#refresh-preview').isVisible(),false);
 await page.locator('#toggle-split').click();
 console.log('First-load guidance, compact rebuild progress, and edits during a build passed');
 // Deleting an imported dependency must remove its copy from Python's filesystem too.
 await page.getByRole('treeitem',{name:/dimensions.py/}).click({button:'right'});
 await page.getByRole('menuitem',{name:'Delete file…'}).click();
 assert.match(await page.locator('#delete-file-description').textContent(),/original file on disk will not be changed/);
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 assert.ok(await page.getByRole('treeitem',{name:/dimensions.py/}).isVisible());
 await page.getByRole('treeitem',{name:/dimensions.py/}).click({button:'right'});
 await page.getByRole('menuitem',{name:'Delete file…'}).click();
 await page.locator('#confirm-delete').click();
 await page.getByRole('treeitem',{name:/dimensions.py/}).waitFor({state:'detached'});
 await page.locator('#refresh-preview').click();
 await page.locator('#error-banner').waitFor({state:'visible'});
 assert.match(await page.locator('#error-message').textContent(),/No module named 'dimensions'/);
 assert.ok(await page.locator('#cad-view canvas').isVisible());
 assert.equal(await page.locator('#preview-progress').isVisible(),false);
 await page.getByRole('treeitem',{name:/model.py/}).click({button:'right'});
 await page.getByRole('menuitem',{name:'Delete file…'}).click();
 await page.locator('#confirm-delete').click();
 await page.getByRole('treeitem',{name:/model.py/}).waitFor({state:'detached'});
 assert.equal(await page.locator('#filename').textContent(),'duck.py');
 console.log('Deletion cancellation, imported dependency removal, and active-file fallback passed');
 await page.locator('#tab-source').click();
 await page.locator('#editor .view-lines').click();
 await page.keyboard.press('Meta+a');
 await page.keyboard.insertText('result = 42');
 await page.locator('#run').click();
 await page.locator('#error-banner').waitFor({state:'visible'});
 console.log('Invalid result correctly rejected');
 await page.locator('#tab-source').click();
 await page.locator('#editor .view-lines').click();
 await page.keyboard.press('Meta+a');
 await page.keyboard.insertText('while True: pass');
 await page.locator('#run').click();
 await page.locator('#cancel').click();
 await page.waitForFunction(()=>!document.querySelector('#run').disabled);
 assert.equal(await page.locator('#preview-progress').isVisible(),false);
 assert.equal(await page.locator('#preview-loading').isVisible(),false);
 console.log('Cancellation released UI');
 await fs.mkdir('test-artifacts',{recursive:true});
 await page.screenshot({path:'test-artifacts/browser.png'});
 // Removing the only open file leaves an editable blank document.
 const emptyPage=await browser.newPage();
 await emptyPage.goto(process.env.TEST_URL||'http://127.0.0.1:5173');
 await emptyPage.getByRole('treeitem').click({button:'right'});
 await emptyPage.getByRole('menuitem',{name:'Delete file…'}).click();
 await emptyPage.locator('#confirm-delete').click();
 await emptyPage.waitForFunction(()=>document.querySelector('#filename').textContent==='untitled.py');
 assert.equal(await emptyPage.getByRole('treeitem').count(),1);
 assert.equal(await emptyPage.locator('#dirty').isVisible(),false);
 await emptyPage.close();
 console.log('Deleting the last open file leaves a blank editor');
} finally {clearInterval(monitor);await browser.close();}
